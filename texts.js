// Asynchronously fetch fresh dynamic text generated by Python random backend
async function fetchPythonRandomText(level = 1) {
  try {
    const res = await fetch(`/api/random-text?level=${encodeURIComponent(level)}`, { cache: 'no-store' });
    if (res.ok) {
      const data = await res.json();
      if (data && data.text) {
        console.log("⚡ Received dynamic text from Python random module:", data.text);
        return data.text;
      }
    }
  } catch (e) {
    // Python backend not running or offline; seamlessly fallback
  }

  // Fallback to local pool
  return getTextForLevel(level);
}

// Synchronous helper for instant level load
function getTextForLevel(level) {
  const safeLevel = Math.max(1, Math.min(100, level || 1));
  let pool;
  if (safeLevel <= 25) {
    pool = TYPING_TEXTS.slice(0, 10);
  } else if (safeLevel <= 50) {
    pool = TYPING_TEXTS.slice(5, 15);
  } else {
    pool = TYPING_TEXTS;
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

function getRandomText() {
  return TYPING_TEXTS[Math.floor(Math.random() * TYPING_TEXTS.length)];
}

